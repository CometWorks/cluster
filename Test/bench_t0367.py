"""T-0367 bench: the two voxel journal paths T-0364 added and no run has exercised - a node replays a storage's
journal (A) after it SKIPPED entries for an asteroid it did not hold, and (B) after the asteroid was REGENERATED
as a new instance under the same entity id; and an edit to a regenerated instance reaches the journal.

Two regular nodes + WA, Cluster-Simple with the live world's procedural asteroids, NO client: the asteroid's cells
are kept generated by /voxel-test-track-point stand-ins and released by /voxel-test-untrack-points.

What the code does (and why phase A is not "node-2 never generated it"):
  * a regular node fetches only the journals of storages in m_storages (VoxelJournalService.SyncLoop), and a
    storage gets there only when the node HOLDS the voxel (Update) or edits it. A node that never generated the
    asteroid never fetches its entries, never skips, and reads the journal from 0 when it generates it - the
    ordinary path. The skip needs: generated once -> unloaded -> entries arrive (Apply: voxel == null ->
    unknownStorageSkips++, m_skippedStorages) -> generated again (ReplayAppearedStorages, reason=generated_after_skip).
  * vanilla unloads a procedural asteroid with its cell only while Save=false (CloseObjectSeed), and any range
    change sets Save=true - the journal's own WriteRange included. So an instance a watermark was applied to never
    unloads by itself; in vanilla it is regenerated only after the voxel trash revert
    (RevertProceduralAsteroidVoxelSettings: Save=false). Phase B does that one step with /voxel-test-revert-settings
    - unless the asteroid unloaded without it, which the bench reports - and lets the generator close and regenerate.

  A1 node-1 tracks a far point; the nearest pristine procedural asteroid is the subject. node-2 generates it
     (same entity id), then releases it: it unloads there. node-1 keeps it.
  A2 cut 1 on node-1 (/voxel-test-cutout-live). The journal is sequenced; node-2 applies the sequence by SKIPPING
     (unknownStorageSkips grows, 'unknown_storage_skipped' logged) and still does not hold the asteroid.
  A3 node-2 generates it again: 'voxel_journal storage_replay=true ... reason=generated_after_skip' once,
     storageReplays +1, and the cut range on node-2 equals node-1's and differs from the pristine hash.
  B1 node-2 releases it again. A modified asteroid stays (reported); Save is reverted, it is tracked and released
     once more and the generator closes it.
  B2 node-2 generates it a third time: 'storage_replay=true ... reason=regenerated' once, storageReplays +1, no
     new skip, the hole is there.
  B3 cut 2 on node-2's regenerated instance, on the far side: the journal sequence grows and node-1 holds the same
     changed range (the RangeChanged subscription is per instance).
No red baseline: df has the fix. Negative controls: the cut hash differs from the pristine hash; node-2 skipped
(unknownStorageSkips > before) and did not hold the asteroid before the replay; the range on node-2 right after it
is generated again is recorded ([INFO], it races the replay scan).
Not covered: the hole after a full cluster restart (ticket's last sentence).

Invocation: cd <tree>/Test && CLUSTER_PACKAGE=<pkg> PYTHONPATH=$PWD uv run python bench_t0367.py <label>
"""
import json
import math
import os
import re
import sys
import time
import urllib.parse
from pathlib import Path

from bench import run_scenario
from cluster import ClusterError, wait_until
from scenarios_core import _lines
from scenarios_ext import _procedural_template

# The helpers below are copies of bench_t0368's: that module runs its scenario at import, so it cannot be imported.
LABEL = sys.argv[1] if len(sys.argv) > 1 else "run"
OUT = Path(os.environ.get("T0367_OUT", "/home/factory/cluster-runs/regression/tools/t0367")) / f"bench-{LABEL}"
OUT.mkdir(parents=True, exist_ok=True)
# Far from the origin: no grid or character tracker of the world reaches the asteroid's cell, so releasing the
# stand-in is what unloads it. Asteroids are generated everywhere (MyInfiniteDensityFunction), WorldSizeKm is 0.
POINT = [float(value) for value in os.environ.get("T0367_POINT", "40000,40000,40000").split(",")]
SEARCH_RADIUS = float(os.environ.get("T0367_SEARCH", "10000"))  # node-1's discovery tracker
TRACK_RADIUS = float(os.environ.get("T0367_TRACK", "1000"))      # node-2's tracker at the asteroid's centre
CUT_RADIUS = float(os.environ.get("T0367_CUT_RADIUS", "3"))
NODES = ("node-1", "node-2")
WRITER, REPLICA = NODES


def node(bench, name: str, path: str, method: str = "GET", timeout: float = 40):
    return bench.cluster.node(name, path, method=method, timeout=timeout)


def attempt(function, default=None):
    try:
        return function()
    except Exception:  # noqa: BLE001 - a polled read that fails is "not yet"
        return default


def poll(predicate, timeout: float, interval: float = 1.0):
    try:
        return wait_until(predicate, timeout, "condition", interval=interval)
    except ClusterError:
        return None


def require(bench, label: str, passed, detail: str = "") -> None:
    """A precondition: everything after it depends on it, so a failure ends the run."""
    if not bench.check(label, bool(passed), detail[:500]):
        raise ClusterError(f"{label}: {detail[:500]}")


def point(values) -> str:
    return "&".join(f"{axis}={value:.3f}" for axis, value in zip("xyz", values))


def asteroids(bench, name: str, where, radius: float) -> list[dict] | None:
    """None: the route did not answer (not the same as an empty list)."""
    answer = attempt(lambda: node(bench, name, f"/voxel-test-asteroids?{point(where)}&radius={radius}"))
    return None if answer is None else answer.get("asteroids") or []


def asteroid(bench, name: str, where, entity: int) -> dict | None:
    return next((row for row in asteroids(bench, name, where, 2000) or [] if int(row["entityId"]) == entity), None)


def absent(bench, name: str, where, entity: int) -> bool:
    """The node answered and does not list the entity."""
    rows = asteroids(bench, name, where, 2000)
    return rows is not None and all(int(row["entityId"]) != entity for row in rows)


def journal(bench, name: str) -> dict:
    return attempt(lambda: node(bench, name, "/voxel-journal-status"), {}) or {}


def applied(status: dict, storage: str) -> int:
    return int((status.get("applied") or {}).get(storage, 0))


def quiet(status: dict) -> bool:
    return all(status.get(key) == 0 for key in ("liveSelfPending", "dirtyRanges", "replaying", "outboundQueued"))


def range_hash(bench, name: str, query: str) -> str | None:
    return (attempt(lambda: node(bench, name, f"/voxel-range-hash?{query}"), {}) or {}).get("hash")


def track(bench, name: str, where, radius: float, record: str) -> None:
    bench.record(record, node(bench, name, f"/voxel-test-track-point?{point(where)}&radius={radius}", "POST"))


def release(bench, name: str, record: str) -> None:
    bench.record(record, node(bench, name, "/voxel-test-untrack-points", "POST"))


def replay_lines(bench, name: str, storage: str) -> list[str]:
    """Console lines (<node>.log); _lines also reads the node's MyLog files, where they do not land today."""
    return _lines(bench, name, rf"voxel_journal storage_replay=true storage={re.escape(storage)} ")


def cut(bench, name: str, entity: int, storage: str, origin, record: str) -> tuple[str, dict]:
    """Where a cut from this point lands: the range-hash query of the 4^3 box at it, and the dry-run answer."""
    path = f"/voxel-test-cutout-live?entity={entity}&{point(origin)}&radius={CUT_RADIUS}"
    probe = node(bench, name, path + "&dry=1", "POST")
    bench.record(record + "-probe", probe)
    voxel = [max(0, v - 2) for v in probe["voxel"]]
    return f"storage={urllib.parse.quote(storage, safe='')}&x={voxel[0]}&y={voxel[1]}&z={voxel[2]}&size=4", {"path": path}


def replayed(bench, storage: str, query: str, want_hash: str, sequence: int, replays_before: int, state: dict) -> bool:
    """node-2 replayed the storage: one more replay counted, none running, watermark back at the tail, the hole there."""
    state["status"] = journal(bench, REPLICA)
    state["hash"] = range_hash(bench, REPLICA, query)
    return (state["status"].get("storageReplays", 0) > replays_before and state["status"].get("replaying") == 0
            and applied(state["status"], storage) == sequence and state["hash"] == want_hash)


def check(bench):
    bench.cluster.config.world_template = _procedural_template(bench)
    bench.start_cluster(nodes=["node-1", "node-2", "wa-1"])
    bench.cluster.post("/automatic/pause")  # nothing moves a partition during the run

    # ---- A1: the asteroid - procedural, pristine, generated on node-2 once and unloaded there ----
    track(bench, WRITER, POINT, SEARCH_RADIUS, "00-track-writer")
    found = poll(lambda: [row for row in asteroids(bench, WRITER, POINT, SEARCH_RADIUS) or []
                          if not row["save"] and not row["contentChanged"]], 90, interval=3)
    bench.record("01-asteroids-writer", asteroids(bench, WRITER, POINT, SEARCH_RADIUS))
    require(bench, f"A1: a pristine procedural asteroid within {SEARCH_RADIUS:.0f} m of {POINT} on {WRITER}", found,
            f"none generated: raise T0367_SEARCH or move T0367_POINT; {json.dumps(asteroids(bench, WRITER, POINT, SEARCH_RADIUS))[:300]}")
    rock = found[0]
    entity, storage, center = int(rock["entityId"]), rock["storage"], rock["center"]
    require(bench, f"A1: {REPLICA} does not hold the asteroid before it tracks it", absent(bench, REPLICA, center, entity),
            json.dumps(asteroids(bench, REPLICA, center, 2000))[:400])
    track(bench, REPLICA, center, TRACK_RADIUS, "02-track-replica-1")
    twin = poll(lambda: asteroid(bench, REPLICA, center, entity), 90, interval=2)
    bench.record("03-asteroid", {WRITER: asteroid(bench, WRITER, center, entity), REPLICA: twin})
    require(bench, f"A1: {REPLICA} generated the same asteroid entity {entity}", twin and twin["storage"] == storage,
            json.dumps(asteroids(bench, REPLICA, center, 2000))[:400])
    time.sleep(5)  # VoxelJournalService.Update has seen the instance: the storage is in the node's fetch set

    # A point outside the asteroid (halfExtent is the half DIAGONAL of its box), and the opposite one for cut 2.
    reach = rock["halfExtent"] + 50
    side_1 = [center[0] + reach, center[1], center[2]]
    side_2 = [center[0] - reach, center[1], center[2]]
    query_1, cut_1 = cut(bench, WRITER, entity, storage, side_1, "04-cut-1")
    query_2, cut_2 = cut(bench, WRITER, entity, storage, side_2, "05-cut-2")
    require(bench, "A1: the two cuts land on different voxels", query_1 != query_2, f"{query_1} / {query_2}")
    pristine_1 = {name: range_hash(bench, name, query_1) for name in NODES}
    pristine_2 = range_hash(bench, WRITER, query_2)
    require(bench, "A1: the pristine range of cut 1 is identical on both nodes",
            pristine_1[WRITER] and pristine_1[WRITER] == pristine_1[REPLICA] and pristine_2, json.dumps(pristine_1))
    pristine = pristine_1[WRITER]

    release(bench, REPLICA, "06-release-replica-1")
    gone = poll(lambda: absent(bench, REPLICA, center, entity), 60)
    require(bench, f"A1: the pristine asteroid unloaded on {REPLICA} once its tracker was released", gone,
            json.dumps(asteroid(bench, REPLICA, center, entity))[:400])
    before = {name: journal(bench, name) for name in (*NODES, "wa-1")}
    bench.record("07-journal-before", before)
    require(bench, "A1: the journal is empty for the asteroid and no replay has run",
            all(applied(before[name], storage) == 0 for name in NODES) and before[REPLICA].get("storageReplays") == 0,
            json.dumps({name: [applied(before[name], storage), before[name].get("storageReplays")] for name in NODES}))
    skips_before = before[REPLICA]["unknownStorageSkips"]

    # ---- A2: cut 1 on node-1; node-2 gets the entries for a storage it does not hold ----
    bench.record("10-cut-1", node(bench, WRITER, cut_1["path"], "POST"))
    state: dict = {}

    def skipped() -> bool:
        state.update({name: journal(bench, name) for name in (*NODES, "wa-1")})
        state["hash"] = range_hash(bench, WRITER, query_1)
        sequence = applied(state[WRITER], storage)
        return (sequence > 0 and quiet(state[WRITER]) and state["hash"] not in (None, pristine)
                and applied(state["wa-1"], storage) == sequence and applied(state[REPLICA], storage) == sequence
                and state[REPLICA].get("unknownStorageSkips", 0) > skips_before)

    settled = poll(skipped, 120, interval=2)
    time.sleep(5)
    settled = settled and skipped()
    bench.record("11-journal-skipped", state)
    sequence_1 = applied(state.get(WRITER) or {}, storage)
    cut_hash = state.get("hash")
    skips = (state.get(REPLICA) or {}).get("unknownStorageSkips", 0)
    require(bench, f"A2: cut 1 is journal sequence {sequence_1} on the World Authority and {WRITER}, and {REPLICA} "
            f"applied it by skipping", settled,
            json.dumps({name: {"applied": applied(state.get(name) or {}, storage),
                               "unknownStorageSkips": (state.get(name) or {}).get("unknownStorageSkips")}
                        for name in (*NODES, "wa-1")}) + f" hash={cut_hash} pristine={pristine}")
    bench.check(f"A2 (control): {WRITER}'s cut range differs from the pristine range", cut_hash != pristine, f"{cut_hash} vs {pristine}")
    bench.check(f"A2 (control): {REPLICA} counted the skip (unknownStorageSkips {skips_before} -> {skips}) and logged it",
                skips - skips_before >= sequence_1
                and len(_lines(bench, REPLICA, rf"unknown_storage_skipped=true storage={re.escape(storage)} ")) >= sequence_1,
                f"{sequence_1} entries")
    bench.check(f"A2 (control): {REPLICA} still does not hold the asteroid and no replay has run",
                absent(bench, REPLICA, center, entity) and state[REPLICA].get("storageReplays") == 0
                and not replay_lines(bench, REPLICA, storage), f"storageReplays={state[REPLICA].get('storageReplays')}")

    # ---- A3: the asteroid appears on node-2 ----
    track(bench, REPLICA, center, TRACK_RADIUS, "20-track-replica-2")
    back = poll(lambda: asteroid(bench, REPLICA, center, entity), 90, interval=0.5)
    require(bench, f"A3: {REPLICA} generated the asteroid again", back, json.dumps(asteroids(bench, REPLICA, center, 2000))[:400])
    print(f"  [INFO] A3: right after it was generated again {REPLICA}'s range is "
          f"{'PRISTINE (the healed asteroid of T-0364)' if range_hash(bench, REPLICA, query_1) == pristine else 'already not pristine'}"
          f" - not asserted, it races the replay scan")
    state = {}
    done = poll(lambda: replayed(bench, storage, query_1, cut_hash, sequence_1, 0, state), 120, interval=2)
    bench.record("21-replay-after-skip", {**state, "asteroid": asteroid(bench, REPLICA, center, entity)})
    lines = replay_lines(bench, REPLICA, storage)
    bench.record("22-replay-lines.txt", "\n".join(lines))
    bench.check(f"A3: {REPLICA} logged one storage_replay for the asteroid, reason=generated_after_skip",
                len(lines) == 1 and "reason=generated_after_skip from=0 " in lines[0], "; ".join(lines)[-300:] or "no line")
    bench.check(f"A3: {REPLICA} counts one replay, finished, watermark back at {sequence_1}",
                (state.get("status") or {}).get("storageReplays") == 1 and (state["status"]).get("replaying") == 0
                and applied(state["status"], storage) == sequence_1,
                json.dumps({key: (state.get("status") or {}).get(key) for key in ("storageReplays", "replaying", "applied")})[:300])
    bench.check(f"A3: the hole is in {REPLICA}'s storage (range hash equals {WRITER}'s, differs from pristine)",
                bool(done) and state.get("hash") == cut_hash == range_hash(bench, WRITER, query_1) and cut_hash != pristine,
                f"{REPLICA}={state.get('hash')} {WRITER}={cut_hash} pristine={pristine}")
    bench.check(f"A3: the replay skipped nothing on {REPLICA}",
                (state.get("status") or {}).get("unknownStorageSkips") == skips, f"{skips} -> {(state.get('status') or {}).get('unknownStorageSkips')}")

    # ---- B1: unload the instance the watermark was applied to ----
    row = asteroid(bench, REPLICA, center, entity) or {}
    print(f"  [INFO] B1: after the replay the asteroid on {REPLICA} has save={row.get('save')} (the journal's write marks it modified)")
    release(bench, REPLICA, "30-release-replica-2")
    forced = not poll(lambda: absent(bench, REPLICA, center, entity), 15)
    print(f"  [INFO] B1: released on {REPLICA}: the modified asteroid "
          + ("STAYED loaded (vanilla keeps Save=true asteroids): reverting Save as the voxel trash revert does"
             if forced else "unloaded by itself - no revert needed"))
    if forced:
        bench.check(f"B1: no replay ran for the instance that stayed on {REPLICA}",
                    len(replay_lines(bench, REPLICA, storage)) == len(lines) and range_hash(bench, REPLICA, query_1) == cut_hash)
        track(bench, REPLICA, center, TRACK_RADIUS, "31-track-replica-3")  # the cell again, so the generator owns the seed
        time.sleep(5)
        reverted = node(bench, REPLICA, f"/voxel-test-revert-settings?entity={entity}", "POST")
        bench.record("32-revert-settings", reverted)
        require(bench, f"B1: Save reverted on {REPLICA}'s asteroid", reverted.get("save") is False, json.dumps(reverted))
        release(bench, REPLICA, "33-release-replica-3")
    require(bench, f"B1: the asteroid unloaded on {REPLICA}", poll(lambda: absent(bench, REPLICA, center, entity), 60),
            json.dumps(asteroid(bench, REPLICA, center, entity))[:400])
    idle = journal(bench, REPLICA)
    require(bench, f"B1: {REPLICA} skipped nothing and replayed nothing while the asteroid was unloaded",
            idle.get("unknownStorageSkips") == skips and idle.get("storageReplays") == 1 and applied(idle, storage) == sequence_1,
            json.dumps({key: idle.get(key) for key in ("unknownStorageSkips", "storageReplays", "applied")})[:300])

    # ---- B2: the regenerated instance ----
    track(bench, REPLICA, center, TRACK_RADIUS, "40-track-replica-4")
    again = poll(lambda: asteroid(bench, REPLICA, center, entity), 90, interval=0.5)
    require(bench, f"B2: {REPLICA} generated the asteroid a third time", again, json.dumps(asteroids(bench, REPLICA, center, 2000))[:400])
    print(f"  [INFO] B2: the new instance has save={again.get('save')}; its range right after generation is "
          f"{'PRISTINE' if range_hash(bench, REPLICA, query_1) == pristine else 'already not pristine'} (not asserted)")
    state = {}
    done = poll(lambda: replayed(bench, storage, query_1, cut_hash, sequence_1, 1, state), 120, interval=2)
    bench.record("41-replay-regenerated", {**state, "asteroid": asteroid(bench, REPLICA, center, entity)})
    lines = replay_lines(bench, REPLICA, storage)
    bench.record("42-replay-lines.txt", "\n".join(lines))
    bench.check(f"B2: {REPLICA} logged a second storage_replay for the asteroid, reason=regenerated",
                len(lines) == 2 and "reason=regenerated from=0 " in lines[1], "; ".join(lines)[-400:] or "no line")
    bench.check(f"B2: {REPLICA} counts two replays, none running, no new skip",
                (state.get("status") or {}).get("storageReplays") == 2 and state["status"].get("replaying") == 0
                and state["status"].get("unknownStorageSkips") == skips,
                json.dumps({key: (state.get("status") or {}).get(key) for key in ("storageReplays", "replaying", "unknownStorageSkips")}))
    bench.check(f"B2: the hole is in the regenerated instance on {REPLICA}",
                bool(done) and state.get("hash") == cut_hash == range_hash(bench, WRITER, query_1),
                f"{REPLICA}={state.get('hash')} {WRITER}={cut_hash} pristine={pristine}")

    # ---- B3: an edit to the regenerated instance reaches the journal ----
    require(bench, f"B3: {REPLICA}'s range of cut 2 is still pristine", range_hash(bench, REPLICA, query_2) == pristine_2,
            f"{range_hash(bench, REPLICA, query_2)} vs {pristine_2}")
    bench.record("50-cut-2", node(bench, REPLICA, cut_2["path"], "POST"))
    state = {}

    def converged() -> bool:
        state.update({name: journal(bench, name) for name in (*NODES, "wa-1")})
        state["hash"] = {name: range_hash(bench, name, query_2) for name in NODES}
        sequences = {applied(state[name], storage) for name in (*NODES, "wa-1")}
        hashes = set(state["hash"].values())
        return (len(sequences) == 1 and min(sequences) > sequence_1 and all(quiet(state[name]) for name in NODES)
                and len(hashes) == 1 and not hashes & {None, pristine_2})

    both = poll(converged, 120, interval=2)
    bench.record("51-journal-cut-2", state)
    sequence_2 = applied(state.get("wa-1") or {}, storage)
    bench.check(f"B3: the cut on {REPLICA}'s regenerated instance was journalled (sequence {sequence_1} -> {sequence_2} on the World Authority)",
                sequence_2 > sequence_1, json.dumps({name: applied(state.get(name) or {}, storage) for name in (*NODES, "wa-1")}))
    bench.check(f"B3: {WRITER} holds the same changed range as {REPLICA}", bool(both),
                f"{json.dumps(state.get('hash'))} pristine={pristine_2}")
    final = {name: range_hash(bench, name, query_1) for name in NODES}
    bench.check("end: cut 1 is still identical on both nodes", set(final.values()) == {cut_hash}, json.dumps(final))
    replays = {name: journal(bench, name).get("storageReplays") for name in NODES}
    bench.check(f"end: {WRITER} never replayed, {REPLICA} replayed twice", replays == {WRITER: 0, REPLICA: 2}, json.dumps(replays))
    bench.exercised(asteroid=storage, entity=entity, center=center, distance=round(math.dist(POINT, center), 1),
                    sequenceCut1=sequence_1, sequenceCut2=sequence_2, skips=skips - skips_before,
                    regeneratedBy="voxel-test-revert-settings" if forced else "vanilla unload", replayLines=lines)


check.regular_nodes = 2
result = run_scenario(check, "T0367-voxel-replay", "voxel journal replay after a skip and after a regenerated asteroid instance", "3", OUT)
(OUT / "verdict.json").write_text(json.dumps(vars(result), default=lambda x: vars(x), indent=2))
raise SystemExit(0 if result.passed else 1)
